// Writes sheet/setup-sheet.gs: a Google Apps Script that builds the gym's Google Sheet
// (tabs, headers, dropdowns, checkboxes, How-to tab) and fills it with the data in data.js.
//   node scripts/make-sheet-setup.mjs
// Then paste sheet/setup-sheet.gs into the sheet (Extensions > Apps Script) and run setUpSheet.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ctx = { window: {}, console };
vm.createContext(ctx);
vm.runInContext(readFileSync(join(root, "site/assets/js/data.js"), "utf8"), ctx);
const HF = ctx.window.HF;

const DAY = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
const time12 = (hhmm) => { const [h, m] = hhmm.split(":").map(Number); return `${h % 12 || 12}:${String(m).padStart(2, "0")} ${h < 12 ? "AM" : "PM"}`; };
const coachName = (id) => (HF.coaches.find((c) => c.id === id) || {}).name || "";

const schedule = [];
for (const d of [1, 2, 3, 4, 5, 6, 0]) for (const [t, cls, coach] of HF.schedule[d] || []) schedule.push([DAY[d], time12(t), HF.classes[cls].name, coachName(coach)]);
const coaches = HF.coaches.map((c) => [c.name, c.role, c.bio || "", !!c.owner, true]);
const events = HF.events.map((e) => [e.date, time12(e.time), e.title, e.text, e.tags.join(", ")]);
const prices = HF.plans.map((p) => [p.name, p.price || "", p.per, p.text, p.cta, !!p.featured]);
const classNames = Object.values(HF.classes).map((c) => c.name);

const seed = JSON.stringify({ schedule, coaches, events, prices, classNames }, null, 2);

const gs = `/**
 * Hardcore Fitness Winter Garden: website sheet setup.
 * Generated by scripts/make-sheet-setup.mjs from site/assets/js/data.js. Don't edit by hand.
 *
 * How to use (one time):
 *   1. Make a new Google Sheet in the gym's Google account. Name it "HCF Winter Garden Website".
 *   2. Extensions > Apps Script. Delete what's there, paste this whole file, click Save.
 *   3. Pick setUpSheet in the function menu and click Run. Allow access when Google asks
 *      (it only touches this one sheet).
 *   4. Back in the sheet: File > Share > Publish to web > Entire document >
 *      Comma-separated values (.csv) > Publish. Copy the link it shows.
 *   5. Send that link to Sergio, plus the tab numbers listed on the "How to" tab.
 *
 * Running it again is safe: a tab that already has rows keeps them. Only empty tabs get the starting data.
 */

var SEED = ${seed};

var RED = "#e31e26";
var DAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"];
var ROLES = ["Owner", "Head Trainer", "Coach"];
var TIME_RULE = '^(1[0-2]|[1-9]):[0-5][0-9] ?([AaPp][Mm])$';

function setUpSheet() {
  var ss = SpreadsheetApp.getActiveSpreadsheet();
  ss.setSpreadsheetTimeZone("America/New_York");
  ss.setSpreadsheetLocale("en_US");

  var coaches = tab_(ss, "Coaches", ["Name", "Role", "Bio (2-3 lines)", "Owner", "Show on site"], SEED.coaches, [180, 130, 420, 80, 110]);
  var schedule = tab_(ss, "Schedule", ["Day", "Time", "Class", "Coach"], SEED.schedule, [120, 100, 140, 180]);
  var events = tab_(ss, "Events", ["Date", "Time", "Title", "Description", "Tags (comma separated)"], SEED.events, [110, 100, 260, 420, 240]);
  var prices = tab_(ss, "Prices", ["Plan", "Price (blank = Ask us)", "Per", "Description", "Button text", "Highlight"], SEED.prices, [170, 170, 150, 420, 200, 100]);

  // Schedule: dropdowns for day, class and coach; time as text like 5:15 AM
  rule_(schedule, "A", SpreadsheetApp.newDataValidation().requireValueInList(DAYS, true).setAllowInvalid(false).setHelpText("Pick a day.").build());
  textTime_(schedule, "B");
  rule_(schedule, "C", SpreadsheetApp.newDataValidation().requireValueInList(SEED.classNames, true).setAllowInvalid(false).setHelpText("Pick a class.").build());
  rule_(schedule, "D", SpreadsheetApp.newDataValidation().requireValueInRange(coaches.getRange("A2:A"), true).setAllowInvalid(false).setHelpText("Pick a coach from the Coaches tab.").build());

  // Coaches: role suggestions, checkboxes
  rule_(coaches, "B", SpreadsheetApp.newDataValidation().requireValueInList(ROLES, true).setAllowInvalid(true).build());
  checkbox_(coaches, "D");
  checkbox_(coaches, "E");
  coaches.getRange("C2:C").setWrap(true);

  // Events: real dates, text times
  dates_(events);
  events.getRange("A2:A").setNumberFormat("yyyy-mm-dd");
  rule_(events, "A", SpreadsheetApp.newDataValidation().requireDate().setAllowInvalid(false).setHelpText("Enter a date, like 2026-12-13.").build());
  textTime_(events, "B");
  events.getRange("D2:D").setWrap(true);

  // Prices: highlight checkbox, plain-text prices like $149
  prices.getRange("B2:B").setNumberFormat("@");
  checkbox_(prices, "F");
  prices.getRange("D2:D").setWrap(true);

  howTo_(ss, [schedule, coaches, events, prices]);

  var blank = ss.getSheetByName("Sheet1");
  if (blank && blank.getLastRow() === 0 && ss.getSheets().length > 1) ss.deleteSheet(blank);
  ss.setActiveSheet(ss.getSheetByName("How to"));
  // A corner note, not a pop-up: a pop-up can leave the script waiting forever if the sheet isn't in front.
  ss.toast("Next: File > Share > Publish to web > Entire document > CSV > Publish.", "Website sheet is ready", 30);
  Logger.log("Done. Tabs: " + [schedule, coaches, events, prices].map(function (t) { return t.getName() + " " + t.getSheetId(); }).join(", "));
}

function tab_(ss, name, headers, rows, widths) {
  var sh = ss.getSheetByName(name) || ss.insertSheet(name);
  sh.getRange(1, 1, 1, headers.length).setValues([headers])
    .setFontWeight("bold").setFontColor("#ffffff").setBackground(RED);
  sh.setFrozenRows(1);
  if (sh.getLastRow() < 2 && rows.length) {
    sh.getRange(2, 1, rows.length, headers.length).setNumberFormat("@").setValues(rows);
  }
  widths.forEach(function (w, i) { sh.setColumnWidth(i + 1, w); });
  var p = sh.getRange(1, 1, 1, headers.length).protect();
  p.setDescription("Column names: the website reads these. Please don't rename them.");
  p.setWarningOnly(true);
  return sh;
}

function rule_(sh, col, rule) { sh.getRange(col + "2:" + col).setDataValidation(rule); }

function textTime_(sh, col) {
  var r = sh.getRange(col + "2:" + col);
  r.setNumberFormat("@");
  r.setDataValidation(SpreadsheetApp.newDataValidation()
    .requireFormulaSatisfied('=OR(' + col + '2="",REGEXMATCH(TO_TEXT(' + col + '2),"' + TIME_RULE + '"))')
    .setAllowInvalid(false).setHelpText("Type a time like 5:15 AM or 6:00 PM.").build());
}

// Starting data arrives as text; turn 2026-12-13 into a real date so the date check passes.
function dates_(sh) {
  var last = sh.getLastRow();
  if (last < 2) return;
  var r = sh.getRange(2, 1, last - 1, 1);
  r.setNumberFormat("yyyy-mm-dd");
  r.setValues(r.getValues().map(function (v) {
    var m = String(v[0]).match(/^(\\d{4})-(\\d{2})-(\\d{2})$/);
    return [m ? new Date(+m[1], +m[2] - 1, +m[3]) : v[0]];
  }));
}

// Checkboxes reach well past the last row, so rows added later get them too.
function checkbox_(sh, col) {
  var last = Math.max(sh.getLastRow(), 2) + 40;
  var r = sh.getRange(col + "2:" + col + last);
  var vals = r.getValues().map(function (v) { return [String(v[0]).toUpperCase() === "TRUE"]; });
  r.setNumberFormat("General").insertCheckboxes().setValues(vals);
}

function howTo_(ss, tabs) {
  var sh = ss.getSheetByName("How to") || ss.insertSheet("How to", 0);
  sh.clear();
  var lines = [
    ["How to update the website"],
    [""],
    ["Change a row and the website updates within about 5 minutes. Refresh the site to see it."],
    ["Schedule: one row per class. Pick the day, type the time like 5:15 AM, pick the class and coach. Add a row to add a class, delete a row to remove it."],
    ["Coaches: add a coach here first, then they show up in the Schedule coach dropdown. Uncheck 'Show on site' to hide someone without deleting them."],
    ["Events: past events disappear from the site on their own. Tags show as small labels, separated by commas."],
    ["Prices: leave Price blank to show 'Ask us'. Check Highlight on the one plan you want to stand out."],
    [""],
    ["Please don't rename the tabs or the red column names. The website reads them."],
    ["Made a mistake? File > Version history > See version history, and restore an earlier version."],
    ["Everything in this sheet shows up publicly on the website. Never put private member info here."],
    [""],
    ["For Sergio (website setup): tab numbers"]
  ];
  tabs.forEach(function (t) { lines.push([t.getName() + ": " + t.getSheetId()]); });
  sh.getRange(1, 1, lines.length, 1).setValues(lines).setWrap(true);
  sh.setColumnWidth(1, 760);
  sh.getRange("A1").setFontSize(16).setFontWeight("bold").setFontColor(RED);
  sh.getRange("A9:A11").setFontWeight("bold");
  sh.getRange("A13").setFontWeight("bold");
}
`;

mkdirSync(join(root, "sheet"), { recursive: true });
writeFileSync(join(root, "sheet/setup-sheet.gs"), gs);
console.log(`Wrote sheet/setup-sheet.gs (${schedule.length} classes, ${coaches.length} coaches, ${events.length} events, ${prices.length} plans).`);
